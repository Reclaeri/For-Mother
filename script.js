  function resolveInteractionPoint(x, y) {
    const isClear = (px, py) => {
      const box = collisionBox(player, px, py);
      return !runtime.obstacles.some((area) => rectHit(box.x, box.y, box.w, box.h, area));
    };
    if (isClear(x, y)) return { x, y };
    // A target is never placed inside a solid object. Search the nearby floor
    // once when it is created; this does not add work to the game loop.
    for (const distance of [42, 72, 104, 138, 174]) {
      for (let angle = 0; angle < Math.PI * 2; angle += Math.PI / 8) {
        const px = x + Math.cos(angle) * distance;
        const py = y + Math.sin(angle) * distance;
        if (isClear(px, py)) return { x: px, y: py };
      }
    }
    return { x, y };
  }
  function autoPortal(x, y, action, el = null, enabled = () => true) {
    const portal = {
      x,
      y,
      radius: 120,
      elapsed: 0,
      triggered: false,
      action,
      el,
      enabled,
    };
    runtime.portals.push(portal);
    addUpdater((dt) => {
      const active =
        enabled() &&
        !dialogActive &&
        !cutsceneActive &&
        !transitionActive &&
        !pauseActive &&
        !miniGameActive;
      const playerBox = collisionBox(player);
      const dx =
        Math.abs(playerBox.x - portal.x) / (portal.radius + playerBox.w / 2);
      const dy =
        Math.abs(playerBox.y - portal.y) /
        (portal.radius * 0.78 + playerBox.h / 2);
      const inside = active && dx * dx + dy * dy <= 1;
      let countdown = els.ui.querySelector(".portal-countdown");
      if (!inside) {
        portal.elapsed = 0;
        countdown?.remove();
        return;
      }
      if (portal.triggered) return;
      portal.elapsed = Math.min(3, portal.elapsed + dt);
      if (!countdown) {
        countdown = document.createElement("div");
        countdown.className = "portal-countdown";
        els.ui.append(countdown);
      }
      countdown.innerHTML = `<span>ANDA TELAH MASUK KE AREA PORTAL</span><strong>${Math.max(1, Math.ceil(3 - portal.elapsed))}</strong><small>Tetap di area untuk berpindah</small>`;
      if (portal.elapsed >= 3) {
        portal.triggered = true;
        countdown.remove();
        action();
      }
    });
    return portal;
  }
