  function safeLoad() {
    try {
      const x = JSON.parse(localStorage.getItem(SAVE_KEY));
      if (!x || typeof x !== "object") return null;
      const d = defaults();
      return synchronizeCollections({
        ...d,
        ...x,
        clues: { ...d.clues, ...x.clues },
        chapters: d.chapters.map((v, i) => !!x.chapters?.[i]),
        medicines: d.medicines.map((v, i) => !!x.medicines?.[i]),
        knowledge: d.knowledge.map((v, i) => !!x.knowledge?.[i]),
        settings: { ...d.settings, ...x.settings },
        chapterProgress: { ...d.chapterProgress, ...x.chapterProgress },
        resume: x.resume && typeof x.resume === "object" ? x.resume : null,
      });
    } catch {
      return null;
    }
  }
  function synchronizeCollections(progress = state) {
    // Saves made before the collection and book existed already know which
    // chapter the player reached. Backfill those earned rewards once, without
    // exposing any future chapter.
    const completedThrough = Math.max(
      progress.currentChapter - 1,
      progress.chapters.reduce((last, done, index) => (done ? index + 1 : last), 0),
    );
    for (let index = 0; index < Math.min(5, completedThrough); index++) {
      progress.medicines[index] = true;
      progress.knowledge[index] = true;
    }
    return progress;
  }
